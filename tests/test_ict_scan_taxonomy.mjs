import {test} from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import vm from 'node:vm';
const read=path=>readFileSync(resolve(path),'utf8');
const source=JSON.parse(read('tools/ict-scan/bronnen/2026-applicatielandschap.json'));
const ctx={};
vm.runInNewContext(read('tools/ict-scan/record-taxonomy.js'),ctx,{filename:'record-taxonomy.js'});
const taxonomy=ctx.IctScanTaxonomy;
const app=read('tools/ict-scan/app.js');
const cards=read('tools/ict-scan/record-cards.js');
const visual=read('tools/ict-scan/visual-explorer.js');
const html=read('tools/ict-scan/index.html');
const build=read('scripts/build_site.py');
test('De gedeelde deterministische indeling wordt op de juiste plaats geladen',()=>{
  assert.ok(html.includes('./record-taxonomy.js?'));
  assert.ok(html.indexOf('./record-taxonomy.js?')<html.indexOf('./app.js?'));
  assert.ok(build.includes('"record-taxonomy.js"'));
  for(const script of [app,cards,visual])assert.ok(script.includes('IctScanTaxonomy.'));
});
test('Alle 76 AI-functies volgen de vastgelegde domeinen en fasen',()=>{
  const edu=source.ai.filter(taxonomy.isClassroomAi),school=source.ai.filter(taxonomy.isSchoolAi);
  assert.equal(source.ai.length,76);
  assert.equal(edu.length,63);
  assert.equal(school.length,13);
  assert.equal(taxonomy.validateAi(source.ai,source.apps).length,0);
  assert.ok(edu.every(r=>taxonomy.phases(r).length));
  assert.ok(school.every(r=>taxonomy.phases(r).length===0));
  assert.ok(school.every(r=>taxonomy.fieldStatus(r,'phase')==='niet-van-toepassing'));
  const used=new Set(edu.flatMap(r=>taxonomy.phases(r)));
  assert.deepEqual([...used].sort(),Array.from(taxonomy.PHASES).sort());
  assert.equal(edu.reduce((n,r)=>n+taxonomy.phases(r).length,0),85);
});
test('Onbekende domeinen worden niet geraden; beheer heeft geen lesfase',()=>{
  const unknown={id:'AI-X',domain:'Nieuw domein',phase:'Instructie'};
  assert.equal(taxonomy.domain(unknown),'unknown');
  assert.equal(taxonomy.isClassroomAi(unknown),false);
  assert.equal(taxonomy.isSchoolAi(unknown),false);
  assert.equal(taxonomy.phases(unknown).length,0);
  assert.equal(taxonomy.validateAi([unknown])[0].code,'UNKNOWN_DOMAIN');
  const admin={id:'AI-Y',domain:'Organisatie en beheer',phase:''};
  assert.equal(taxonomy.fieldLabel('teacher',admin,'Controle door docent'),'Controle door medewerker of beheerder');
  assert.equal(taxonomy.fieldStatus(admin,'student'),'niet-van-toepassing');
  assert.equal(taxonomy.validateAi([{...admin,phase:'Instructie'}])[0].code,'PHASE_NOT_APPLICABLE');
  assert.equal(taxonomy.validateAi([{id:'AI-Z',domain:'Onderwijsleerproces',phase:'Proefwerk nakijken'}])[0].code,'UNKNOWN_PHASE');
});
test('Kaart, grafieken en rapportage gebruiken dezelfde betekenisregels',()=>{
  assert.ok(cards.includes("IctScanTaxonomy.fieldLabel("));
  assert.ok(cards.includes("IctScanTaxonomy.fieldStatus("));
  assert.ok(app.includes('IctScanTaxonomy.chartPhases('));
  assert.ok(app.includes('IctScanTaxonomy.phases(x).includes(state.phase)'));
  assert.ok(visual.includes('IctScanTaxonomy.chartPhases('));
  assert.ok(app.includes('IctScanTaxonomy.isSchoolAi('));
  assert.ok(!visual.includes("item.phase||'Niet ingedeeld'"));
});
