import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {DatabaseSync} from 'node:sqlite';
import {ictEditor} from '../services/html-galerij/src/ict-editor.js';
import {sha256} from '../services/html-galerij/src/auth.js';

test('De scan wisselt een code eenmaal om en verliest toegang bij centraal afmelden', async()=>{
  const db=new DatabaseSync(':memory:');
  db.exec(readFileSync(new URL('../services/html-galerij/schema.sql',import.meta.url),'utf8'));
  const DB={prepare(sql){return {bind(...args){return {first:()=>db.prepare(sql).get(...args),run:()=>db.prepare(sql).run(...args)};}};},batch:async statements=>statements.map(s=>s.run())};
  const owner='beheer@example.test', env={DB,GALLERY_PASSWORD_HASH:'fixture',GALLERY_ADMIN_EMAIL:owner};
  const cookie='a'.repeat(64), session=await sha256('fixture:'+cookie);
  db.prepare('INSERT INTO gallery_sessions VALUES(?,?,?)').run(session,owner,Math.floor(Date.now()/1000)+600);
  const origin='https://beheer.example.test';
  const invoke=(path,headers,user=null)=>ictEditor(new Request(origin+path,{method:'POST',headers}),env,user,path);
  const form={origin,cookie:'__Host-eai_gallery_session='+cookie};
  assert.equal((await invoke('/ict-editor/open',form)).status,403);
  assert.equal((await invoke('/ict-editor/open',{...form,origin:'https://example.test'},owner)).status,403);
  const page=await invoke('/ict-editor/open',form,owner);
  const code=(await page.text()).match(/name="code" value="([a-f0-9]{64})"/)[1];
  const exchange=()=>invoke('/ict-editor/redeem',{authorization:'Bearer '+code});
  const {token}=await (await exchange()).json();
  assert.equal((await exchange()).status,403);
  const check=()=>invoke('/ict-editor/check',{authorization:'Bearer '+token});
  assert.equal((await check()).status,200);
  db.prepare('DELETE FROM gallery_sessions WHERE token_hash=?').run(session);
  assert.equal((await check()).status,403);
  db.close();
});
