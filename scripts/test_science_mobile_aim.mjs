import assert from 'node:assert/strict';
import {chromium,webkit} from 'playwright';
import {spawn} from 'node:child_process';
import {mkdirSync} from 'node:fs';
const root=process.argv[2]||'site-build',engine=process.argv[3]==='webkit'?webkit:chromium;
const port=8873,base='http://127.0.0.1:'+port;
const server=spawn('python3',['-m','http.server',String(port),'--bind','127.0.0.1','--directory',root],{stdio:'ignore'});
const delay=ms=>new Promise(r=>setTimeout(r,ms));
let browser;
mkdirSync('test-results',{recursive:true});
try{
 let ready=false;
 for(let i=0;i<85;i++){try{if((await fetch(base+'/tools/science-observatory/labs/natuurkunde/')).ok){ready=true;break}}catch{}await delay(100)}
 assert(ready,'Natuurkunde page exists');
 browser=await engine.launch({headless:true});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:2,isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base+'/tools/science-observatory/labs/natuurkunde/#projectile',{waitUntil:'load'});
 await page.waitForFunction(()=>document.querySelector('#labTitle').textContent==='Schuine worp');
 assert(await page.locator('#mobileQuick').isVisible(),'Compacte richtknoppen zijn direct zichtbaar');
 assert(await page.locator('#quick-v').isVisible(),'Fijne snelheid kan rechtstreeks ingesteld worden');
 assert(await page.locator('#inquiryAction').isVisible(),'Gooi-knop blijft op het scherm');
 assert(!(await page.locator('#mobileAim').isVisible()),'Grote dubbele bediening is verdwenen');
 const geometry=await page.evaluate(()=>{
  const c=document.querySelector('#scene'),g=sceneViewport(c),f=projectileMobileFrame(state.p),r=document.querySelector('#stage').getBoundingClientRect();
  return {g,f,stage:{top:r.top,bottom:r.bottom,height:r.height},scroll:document.documentElement.scrollHeight,screen:innerHeight};
 });
 assert.equal(geometry.g.virtualWidth,560);
 assert.equal(geometry.g.virtualHeight,520);
 assert(geometry.g.left>=-1&&geometry.g.top>=-1,'Geen vervorming van de scène');
 assert(geometry.f.targetX>100&&geometry.f.targetX<520,'Mat staat binnen de scène');
 assert(geometry.scroll<=geometry.screen+1,'Geen pagina-scroll');
 await page.locator('#quickMore').click();
 await page.locator('#num-angle').fill('45.5');await page.locator('#num-angle').dispatchEvent('change');
 assert.equal(await page.locator('#num-angle').inputValue(),'45.5');
 await page.locator('#closeMobileSettings').click();
 const touch=await page.evaluate(()=>{
  const c=document.querySelector('#scene'),f=projectileMobileFrame(state.p),g=sceneViewport(c),r=c.getBoundingClientRect();
  return {x:r.x+g.left+f.handle.x*g.scale,y:r.y+g.top+f.handle.y*g.scale};
 });
 await page.mouse.move(touch.x,touch.y);await page.mouse.down();
 await page.mouse.move(touch.x+20,touch.y+14,{steps:6});await page.mouse.up();
 const moved=await page.evaluate(()=>({angle:state.p.angle,v:state.p.v}));
 assert(Math.abs(moved.angle-45.5)>.4||Math.abs(moved.v-18)>.1,'Richtgreep wijzigt hoek of snelheid');
 await page.locator('#inquiryAction').click();
 await page.waitForFunction(()=>mission.complete===true,null,{timeout:14000});
 assert.equal(await page.evaluate(()=>mission.shots.length),1,'Eerste worp blijft bewaard');
 await page.locator('#scene').screenshot({path:'test-results/science-mobile-fixed-landed.png'});
 await page.locator('#inquiryAction').click();
 assert(await page.evaluate(()=>!mission.launched&&!mission.complete&&mission.shots.length===1),'Nieuwe poging behoudt eerdere worp');
 await page.locator('#quick-v').fill('35');await page.locator('#quick-v').dispatchEvent('change');
 const before=await page.evaluate(()=>projectileMobileFrame(state.p).scale);
 await page.evaluate(()=>{mission.view='overview';render()});
 const after=await page.evaluate(()=>projectileMobileFrame(state.p).scale);
 assert(after<=before,'Bij uitzoomen worden meters niet uitgerekt');
 await page.goto(base+'/tools/science-observatory/labs/natuurkunde/#interference',{waitUntil:'load'});
 await page.waitForFunction(()=>state.id==='interference');
 assert(await page.locator('#quick-v').count()===0,'Richtbediening is uniek per proef');
 assert(await page.locator('#mobileQuick').isVisible(),'Andere proeven houden compacte instellingen');
 assert.deepEqual(errors,[],'Geen runtime-fouten');
 console.log('Mobiele Schuine Worp: richten, schieten, resultaten en exacte schaal behouden');
}finally{if(browser)await browser.close();server.kill();}
