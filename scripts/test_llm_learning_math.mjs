// Rekenkundige controles voor de gratis, lokaal uitgevoerde leervoorbeelden.
import assert from 'node:assert/strict';
import '../assets/llm-learning-math.js';
const m=globalThis.EAILearningMath;
assert(m,'De lokale leerrekenmodule ontbreekt');
const p=m.softmax([2.45,1.50,.82,.24],.8);
assert(Math.abs(p.reduce((a,b)=>a+b,0)-1)<1e-12,'De kansen tellen op tot 100%');
assert(p.every(x=>x>0&&Number.isFinite(x)),'De kansen moeten geldig zijn');
const hot=m.softmax([2.45,1.50,.82,.24],1.6);
assert(hot[0]<p[0],'Meer temperatuur maakt deze voorbeeldverdeling vlakker');
assert.deepEqual(m.tokenVector(101),m.tokenVector(101),'Een token krijgt dezelfde voorbeeldvector');
assert.notDeepEqual(m.tokenVector(101),m.tokenVector(102),'Andere token-ID kan andere vector opleveren');
const ids=[101,204,309,402];
const first=m.miniTrace(ids,0,0,32).current;
assert.equal(first.attention.weights.length,1,'Geen toekomstige tokens in attention');
assert(Math.abs(first.attention.weights[0]-1)<1e-12,'Enig bereikbaar token heeft gewicht 1');
const last=m.miniTrace(ids,3,3,32).current;
assert.equal(last.attention.weights.length,4,'Vier bereikbare tokenposities');
assert(Math.abs(last.attention.weights.reduce((a,b)=>a+b,0)-1)<1e-12,'Attention-gewichten sommeren tot 1');
assert.equal(last.experts.selected.length,4,'Router kiest precies vier experts');
assert.equal(new Set(last.experts.selected.map(e=>e.expert)).size,4,'Geen dubbele experts');
assert(last.experts.selected.every(e=>e.expert>=0&&e.expert<32),'Expert-index binnen model');
assert(Math.abs(last.experts.selected.reduce((a,e)=>a+e.weight,0)-1)<1e-12,'Routergewichten sommeren tot 1');
assert(last.input.every(Number.isFinite)&&last.afterAttention.every(Number.isFinite)&&last.result.every(Number.isFinite),'Geen ongeldige activatie in het miniatuurmodel');
assert.notDeepEqual(last.input,last.result,'Een laag verandert de vier getallen');
assert.deepEqual(m.miniTrace(ids,3,3,32),m.miniTrace(ids,3,3,32),'Zelfde invoer, zelfde rekenuitkomst');
assert.equal(m.miniTrace(ids,3,0,128).current.experts.selected.length,4,'Ook 128 experts top-4');
console.log('LLM leervoorbeelden: wiskundige controles geslaagd');
